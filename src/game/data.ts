// 要新增章節，就在 chapters 裡多加一個；要新增卡片，就在 cards 裡多加一張（圖片放 public/game/cards/）。
// 文字裡的 \n\n 代表換一個段落。

export interface Card {
  id: string;
  name: string;
  img: string;
  quote: string; // 取自戴戴筆記「導師的點滴心語」
}

export interface Choice {
  text: string;
  result: string;
  merit: number; // 陰德，玩家看不到
  cards?: string[]; // 這個選擇會得到的卡片 id（可以不只一張）
  karma?: string; // 惡報：會在下一章開頭出現
  shorten?: number; // 大惡：折壽，這一生少玩幾回
  realm?: RealmId; // 壞選項屬於哪一道
}

export interface Chapter {
  id: string;
  stage: StageId; // 屬於人生哪個階段
  roles?: string[]; // 只有選了這些職業才會遇到（world.ts 的 roles id）；不寫就是大家都會遇到
  image?: string; // 故事的插圖，例如 '/game/stories/deepfake-boss.jpg'；不寫就只有文字
  epilogue?: string; // 不管選哪個選項，看完結果之後都會出現的一段話
  epilogueSource?: { label: string; url?: string }; // 那段話的出處
  hint: { quote: string; source: string }; // 「停看聽」求救鈕顯示的筆記句子
  title: string;
  text: string;
  choices: Choice[];
}

export interface Trial {
  id: string;
  title: string;
  text: string;
  counters: string[]; // 能抵抗這個考驗的卡片 id
  pass: string;
  fail: string;
}

